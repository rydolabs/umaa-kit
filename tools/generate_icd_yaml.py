#!/usr/bin/env python3
"""Deterministic, conservative UMAA 6.0 six-ICD catalog -> YAML projection.

The reviewed 53-service/113-topic catalog is NOT full normative ICD prose.
No DDS Topic string, QoS, command session field, official IDL validation, or
Collection relationship may be inferred from a type/operation name.
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path
from typing import Any

from tools.umaa_service_contracts import CATALOG, _read_catalog

REPO = Path(__file__).resolve().parents[1]
DEFAULT_OUT = REPO / "contracts/umaa6"
DOMAINS = {
    "EO": "Engineering Operations",
    "MO": "Maneuver Operations",
    "MM": "Mission Management",
    "SA": "Situational Awareness",
    "SEM": "Sensor and Effector Management",
    "SO": "Support Operations",
}
REFERENCE_KIND = "secondary-transcription"
SCHEMA_VERSION = "umaa.dev/v1alpha1"
HEADER = ("# AUTOGENERATED from catalog/umaa6-six-icd-reviewed.json.\n"
          "# Reviewed mapping ONLY; NOT full ICD prose, official TypeSupport, "
          "key/QoS or wire conformance.\n")


def yaml_text(value: Any) -> str:
    """Render a strict, auditable JSON-scalar subset of YAML 1.2."""
    output: list[str] = []

    def visit(item: Any, depth: int) -> None:
        space = " " * depth
        if isinstance(item, dict):
            for k, v in item.items():
                if not isinstance(k, str) or not k.replace("_", "").replace("-", "").isalnum():
                    raise ValueError("unsafe YAML mapping key: " + repr(k))
                if isinstance(v, dict) and v:
                    output.append(f"{space}{k}:")
                    visit(v, depth + 2)
                elif isinstance(v, list) and v:
                    output.append(f"{space}{k}:")
                    visit(v, depth + 2)
                else:
                    output.append(f"{space}{k}: {scalar(v)}")
        elif isinstance(item, list):
            for v in item:
                if isinstance(v, (dict, list)) and v:
                    output.append(f"{space}-")
                    visit(v, depth + 2)
                else:
                    output.append(f"{space}- {scalar(v)}")
        else:
            raise TypeError("nested scalar not expected")

    def scalar(v: Any) -> str:
        if isinstance(v, (dict, list)) and v:
            raise TypeError("expected empty collection or scalar")
        return json.dumps(v, ensure_ascii=False, separators=(",", ":"))

    visit(value, 0)
    return HEADER + "\n".join(output) + "\n"


def topic_aliases(service: dict) -> tuple[dict, dict]:
    topics: dict[str, dict] = {}
    by_type: dict[str, str] = {}
    counters: dict[str, int] = {}
    for side, direction in (("provider_topics", "provider-to-consumer"),
                            ("consumer_topics", "consumer-to-provider")):
        for item in service[side]:
            role = item["role"].replace("_", "-")
            alias_base = {"execution-status": "executionStatus"}.get(role, role)
            counters[alias_base] = counters.get(alias_base, 0) + 1
            alias = f"{alias_base}{counters[alias_base]:02d}"
            topics[alias] = {
                "catalogId": item["name"],
                "idlType": item["type"],
                # Catalog ID or IDL type is NOT proof of actual DDS Topic name.
                "ddsTopicName": None,
                "role": role,
                "direction": direction,
                "keyFields": None,
                "qosProfileRef": None,
            }
            if item["type"] in by_type:
                raise ValueError("duplicate scoped Topic type: " + item["type"])
            by_type[item["type"]] = alias
    return topics, by_type


def build_protocols(service: dict, by_type: dict[str, str]) -> list[dict]:
    pattern = service["pattern"]
    if pattern == "request_reply_without_query_data":
        reports = [by_type[x["type"]] for x in service["provider_topics"]
                   if x["role"] == "report"]
        if not reports:
            raise ValueError("queryless service missing Report types")
        return [{
            "id": "querylessReport",
            "kind": "request-reply",
            "mode": "without-query-data",
            "rulesRef": "umaa://flows/request-reply-without-query-data@6.0",
            "bindings": {"reports": reports},
        }]
    if pattern == "publish_subscribe":
        reports = [by_type[x["type"]] for x in service["provider_topics"]
                   if x["role"] == "report"]
        return [{
            "id": "reportSubscription",
            "kind": "publish-subscribe",
            "rulesRef": "umaa://flows/publish-subscribe@6.0",
            "bindings": {"reports": reports},
        }]
    if pattern != "command_response":
        raise ValueError("unsupported pattern " + str(pattern))
    groups = service.get("command_groups")
    if not groups:
        roles = {}
        for side in ("provider_topics", "consumer_topics"):
            for topic in service[side]:
                roles.setdefault(topic["role"], []).append(topic["type"])
        if any(len(roles.get(r, [])) != 1 for r in ("command", "ack", "status")):
            raise ValueError("ambiguous Command grouping requires reviewed groups")
        groups = [{"name": "Command", **{r: roles[r][0] for r in
                   ("command", "ack", "status")}}]
    result = []
    for group in groups:
        binding = {role: by_type[group[role]] for role in ("command", "ack", "status")}
        # One execution-status side topic is linked only when there is a
        # single command group; multi-group association is not inferred.
        extras = [item for item in service["provider_topics"]
                  if item["role"] == "execution_status"]
        if len(groups) == 1 and len(extras) == 1:
            binding["executionStatus"] = by_type[extras[0]["type"]]
        result.append({
            "id": group["name"],
            "kind": "command-response",
            "rulesRef": "umaa://flows/command-response@6.0",
            "bindings": binding,
        })
    return result


def service_clause(service: dict) -> str:
    """Use the actual 5.1.N or 6.1.N service heading, not a generic chapter."""
    headings = [clause for clause in service["clauses"]
                if __import__("re").fullmatch(r"(?:5|6)\\.1\\.\\d+", clause)]
    if len(headings) != 1:
        raise ValueError("ambiguous or missing service section: " + service["name"])
    return headings[0]


def build_service(service: dict, catalog: dict) -> dict:
    fq_name = service["name"]
    _, domain, title = fq_name.split("::")
    if domain not in DOMAINS:
        raise ValueError("unreviewed domain " + domain)
    topics, by_type = topic_aliases(service)
    # Operation->Topic is intentionally unresolved: catalog only records
    # literal names, not every ICD operation relation or all side effects.
    operations = {
        op: {"kind": "unresolved", "topicRef": None, "sourceClause": None}
        for op in service["operations"]
    }
    return {
        "apiVersion": SCHEMA_VERSION,
        "kind": "Service",
        "metadata": {"id": fq_name, "title": title, "revision": 1},
        "sources": {
            "icd": {
                "document": f"UMAA-SPEC-{domain}ICD",
                "version": "6.0",
                "clauses": service["clauses"],
                "originalSha256": None,
                "reference": {"kind": REFERENCE_KIND,
                              "revision": catalog["ledger_source_revision"]},
            },
            "idl": {"release": "6.0", "bundleSha256": None},
        },
        "documentation": {
            "summary": "Service and interface identities from reviewed ICD mapping; full prose, tables and figures not imported.",
            "sections": [{
                "clause": service_clause(service),
                "title": title,
                "text": "",
            }],
            "tables": [],
            "figures": [],
        },
        "spec": {
            "topics": topics,
            "operations": operations,
            "protocols": build_protocols(service, by_type),
            "collections": [],
            "specializations": [],
            "unresolvedCollectionTypes": service.get("collection_topics", []),
            "requirements": [],
        },
        "reviewedMapping": {
            "catalogVersion": catalog["catalog_version"],
            "originalPattern": service["pattern"],
            "sourceNote": service.get("source"),
        },
        "verification": {
            "icdMappingReviewed": service["icd_reviewed"] is True,
            "officialIdlVerified": service["official_idl_verified"] is True,
            "ddsQosVerified": service["dds_qos_verified"] is True,
            "ddsBehaviorVerified": service["dds_behavior_verified"] is True,
        },
        "extensions": {},
    }


def build_icd(domain: str, services: list[dict], catalog: dict) -> dict:
    if domain not in DOMAINS:
        raise ValueError("unreviewed ICD domain")
    unique = set()
    sections = []
    for svc in services:
        clause = service_clause(svc)
        if clause in unique:
            raise ValueError("repeated service clause " + clause)
        unique.add(clause)
        sections.append({
            "clause": clause,
            "title": svc["name"].split("::")[-1],
            # Empty here means not yet extracted from authoritative prose,
            # not "the source contains no paragraphs or requirements".
            "paragraphs": [],
            "tables": [],
            "figures": [],
            "requirements": [],
        })
    return {
        "apiVersion": SCHEMA_VERSION,
        "kind": "ICD",
        "metadata": {
            "id": f"UMAA-SPEC-{domain}ICD",
            "title": f"{DOMAINS[domain]} ICD",
            "revision": 1,
        },
        "sources": {"document": {
            "id": f"UMAA-SPEC-{domain}ICD",
            "version": "6.0",
            "originalSha256": None,
            "reference": {"kind": REFERENCE_KIND,
                          "revision": catalog["ledger_source_revision"]},
        }},
        "spec": {"sections": sections,
                 "services": [svc["name"] for svc in services]},
        "extensions": {},
    }


def expected_files(catalog: dict) -> dict[str, str]:
    records: dict[str, list[dict]] = {d: [] for d in DOMAINS}
    result: dict[str, str] = {}
    for service in catalog["services"]:
        _, domain, name = service["name"].split("::")
        records[domain].append(service)
        rel = f"services/{domain}/{name}.yaml"
        if rel in result:
            raise ValueError("duplicate generated path: " + rel)
        result[rel] = yaml_text(build_service(service, catalog))
    for domain, services in records.items():
        if not services:
            raise ValueError("missing ICD from reviewed catalog: " + domain)
        result[f"icd/{domain}.yaml"] = yaml_text(build_icd(domain, services, catalog))
    return dict(sorted(result.items()))


def write_files(output: Path, files: dict[str, str], check: bool = False) -> None:
    if output.is_symlink():
        raise ValueError("output root is a symlink")
    for path, expected in files.items():
        target = output / path
        if target.is_symlink():
            raise ValueError("refusing symlink output " + str(target))
        if check:
            if not target.is_file() or target.read_text(encoding="utf-8") != expected:
                raise ValueError("generated YAML out of date: " + str(target))
        else:
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_text(expected, encoding="utf-8", newline="\n")
    extras = set(p.relative_to(output).as_posix()
                 for p in output.rglob("*.yaml")) - set(files) if output.exists() else set()
    if extras:
        raise ValueError("unexpected YAML in generated area: " + repr(sorted(extras)))


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--catalog", type=Path, default=CATALOG)
    parser.add_argument("--out", type=Path, default=DEFAULT_OUT)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    catalog, digest = _read_catalog(args.catalog)
    files = expected_files(catalog)
    write_files(args.out, files, check=args.check)
    count = sum(name.startswith("services/") for name in files)
    topics = sum(len(s["provider_topics"]) + len(s["consumer_topics"])
                 for s in catalog["services"])
    print(f"ICD_YAML_PASS: icds={len(DOMAINS)} services={count} topics={topics} "
          f"catalog_sha256={digest} mode={'check' if args.check else 'generate'}")


if __name__ == "__main__":
    main()
