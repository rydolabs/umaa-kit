#!/usr/bin/env python3
"""Generate a *strictly scoped* EngineControl user module from official Cyclone TypeSupport.

The AUVSI IDL is consumed outside the repo and must be generated by idlc first.
This is a validated EngineControl ignition-state subset, not all UMAA fields.
The generated module is DDS-free; the Host remains responsible for UMAA behavior.
"""
import argparse
import json
import pathlib
import re

from tools.official_icd_evidence import audit, SourceError
from tools.umaa_contract_ir import load_service

SERVICE = "UMAA::EO::EngineControl"
SCHEMA = "umaa-6.0-enginecontrol-ignition-subset-v1"
ENUM = "UMAA_Common_MaritimeEnumeration_IgnitionControlEnumModule"


def inspect(root: pathlib.Path):
    c = root / "UMAA/EO/EngineControl/EngineCommandType.h"
    e = root / "UMAA/Common/MaritimeEnumeration/MaritimeEnumerationSets.h"
    if not c.is_file() or not e.is_file():
        raise ValueError("official generated EngineCommandType/MaritimeEnumeration TypeSupport missing")
    source = c.read_text(encoding="utf-8")
    em = e.read_text(encoding="utf-8")
    if not re.search(r"typedef struct UMAA_EO_EngineControl_EngineCommandType\s*\{", source):
        raise ValueError("unexpected generated official EngineCommandType definition")
    for clause in (
        rf"{ENUM}_IgnitionControlEnumType\s+state\s*;",
        r"UMAA_Common_Measurement_NumericGUID\s+sessionID\s*;",
        r"struct UMAA_Common_IdentifierType\s+source\s*;",
        r"struct UMAA_Common_IdentifierType\s+destination\s*;",
        r"struct UMAA_Common_Measurement_DateTime\s+timeStamp\s*;",
    ):
        if not re.search(clause, source):
            raise ValueError("official EngineControl IDL mapping changed: " + clause)
    enum = re.search(rf"typedef enum {ENUM}_IgnitionControlEnumType\s*\{{(.*?)\}}", em, re.S)
    if not enum:
        raise ValueError("official IgnitionControl enumeration missing")
    entries = [v.strip() for v in enum.group(1).split(",") if v.strip()]
    values = [re.fullmatch(rf"{ENUM}_(OFF|RUN)\s*(?:=\s*(\d+))?", e) for e in entries]
    if len(values) != 2 or any(v is None for v in values) or [v.group(1) for v in values] != ["OFF", "RUN"]:
        raise ValueError("unsupported ignition enum expansion; update service catalog and tests")
    ids = [int(v.group(2)) if v.group(2) else n for n,v in enumerate(values)]
    if ids != [0,1]:
        raise ValueError("unexpected official IgnitionControl enum numeric values")
    return ids



def verify_engine_source_contract(yaml_path: pathlib.Path,
                                  archive_path: pathlib.Path, digest: str) -> dict:
    """Validate original IDL Topic/Keys and YAML Command binding, not protocol QoS."""
    if not re.fullmatch(r"[0-9a-f]{64}", digest):
        raise SourceError("exact external archive SHA-256 pin required")
    evidence=audit(archive_path,[yaml_path])
    if evidence["archiveSha256"] != digest or evidence["issues"]:
        raise SourceError("EngineControl official IDL source mismatch")
    doc, yaml_sha=load_service(yaml_path)
    if (doc["metadata"]["id"] != SERVICE or
        doc["sources"]["idl"]["bundleSha256"] != digest):
        raise SourceError("EngineControl YAML has wrong Service or IDL source pin")
    protocols=doc["spec"]["protocols"]
    if (len(protocols)!=1 or protocols[0]["kind"]!="command-response" or
        protocols[0]["bindings"]!={"command":"command01","ack":"ack01",
                                   "status":"status01"}):
        raise SourceError("EngineControl protocol bindings differ from scoped generator")
    expected={
        "command01":("EngineCommandType","command","consumer-to-provider",
                     ["source","sessionID","destination"]),
        "ack01":("EngineCommandAckReportType","ack","provider-to-consumer",
                 ["source","sessionID"]),
        "status01":("EngineCommandStatusType","status","provider-to-consumer",
                    ["source","sessionID"]),
    }
    topics=doc["spec"]["topics"]
    if set(topics)!=set(expected):
        raise SourceError("EngineControl Topic aliases incomplete")
    for alias,(name,role,direction,keys) in expected.items():
        topic=topics[alias]
        fq=SERVICE+"::"+name
        if (topic["idlType"]!=fq or topic["ddsTopicName"]!=fq or
            topic["role"]!=role or topic["direction"]!=direction or
            topic["keyFields"]!=keys):
            raise SourceError("EngineControl source-derived Topic/Key mismatch: "+alias)
    if (doc["verification"]["ddsQosVerified"] or
        doc["verification"]["ddsBehaviorVerified"]):
        raise SourceError("ignition subset cannot certify full QoS/protocol")
    return {"scope":"ENGINECONTROL_IGNITION_SUBSET_ONLY",
      "serviceId":SERVICE,"archiveSha256":digest,
      "candidateYamlSha256":yaml_sha,"verifiedNativeTopicTypes":3,
      "completeProtocolGenerated":False,"reviewedPerServiceQos":False}

def generate(root: pathlib.Path, out: pathlib.Path):
    inspect(root)
    out.mkdir(parents=True, exist_ok=True)
    header = out / "engine_control_handler.hpp"
    glue = out / "engine_control_module.cpp"
    header.write_text("""// GENERATED; user implements only EngineControlHandler in a separate file.
#pragma once
#include <cstdint>
#include <memory>
namespace umaa::generated {
enum class IgnitionState : std::int32_t { Off=0, Run=1 };
class EngineControlHandler {
 public:
  virtual ~EngineControlHandler() = default;
  virtual bool set_ignition(IgnitionState state) = 0;
  virtual bool stop() = 0;
};
std::unique_ptr<EngineControlHandler> make_engine_handler();
} // namespace umaa::generated
""", encoding="utf-8")
    glue.write_text("""// GENERATED from verified official EngineCommandType + explicit service mapping.
// No DDS instances or protocol state machines are part of a user module.
#include "engine_control_handler.hpp"
#include "umaa/module_api.h"
#include <new>
#include <memory>
using namespace umaa::generated;
namespace {
struct Impl { std::unique_ptr<EngineControlHandler> handler; bool running{false}; };
void* create() {
  try {
    auto h = make_engine_handler();
    if(!h) return nullptr;
    return new(std::nothrow) Impl{std::move(h),false};
  } catch (...) {return nullptr;}
}
int32_t start(void* v) {
  if(!v) return -1;static_cast<Impl*>(v)->running=true;return 0;
}
int32_t invoke(void* v,int32_t operation,int64_t input,int64_t* output) {
  if(!v || !output || operation!=1 || (input!=0 && input!=1))return -1;
  auto& instance=*static_cast<Impl*>(v);
  if(!instance.running)return -1;
  try {
    if(!instance.handler->set_ignition(static_cast<IgnitionState>(input))) return -1;
    *output=input;return 0;
  } catch (...) {return -1;}
}
int32_t stop(void* v) {
  if(!v)return -1;
  auto& instance=*static_cast<Impl*>(v);
  try {
    if(instance.running && !instance.handler->stop())return -1;
    instance.running=false;return 0;
  } catch (...) {return -1;}
}
void destroy(void* v){delete static_cast<Impl*>(v);}
const UmaaModuleV1 api={UMAA_MODULE_ABI_VERSION,sizeof(UmaaModuleV1),
  "UMAA::EO::EngineControl","umaa-6.0-enginecontrol-ignition-subset-v1",
  &create,&start,&invoke,&stop,&destroy};
}
extern "C" UMAA_MODULE_EXPORT const UmaaModuleV1* umaa_get_module_v1(uint32_t version){
  return version==UMAA_MODULE_ABI_VERSION?&api:nullptr;
}
""", encoding="utf-8")
    print(f"OFFICIAL_ENGINE_HANDLER_GENERATED {header} {glue} verified official ignition enum OFF=0 RUN=1")


def main():
    p = argparse.ArgumentParser()
    p.add_argument("--type-root", required=True, type=pathlib.Path)
    p.add_argument("--output", required=True, type=pathlib.Path)
    p.add_argument("--yaml", type=pathlib.Path)
    p.add_argument("--zip", type=pathlib.Path)
    p.add_argument("--expect-sha256")
    a = p.parse_args()
    if any((a.yaml,a.zip,a.expect_sha256)) and not all((a.yaml,a.zip,a.expect_sha256)):
        p.error("--yaml, --zip and --expect-sha256 must be supplied together")
    source=verify_engine_source_contract(a.yaml,a.zip,a.expect_sha256) if a.yaml else None
    generate(a.type_root,a.output)
    if source:
        (a.output/"engine_control_source_evidence.json").write_text(
            json.dumps(source,sort_keys=True,indent=2)+"\n",encoding="utf-8")
        print("OFFICIAL_ENGINE_YAML_IDL_GENERATION_PASS",source["verifiedNativeTopicTypes"])


if __name__ == "__main__":
    main()
