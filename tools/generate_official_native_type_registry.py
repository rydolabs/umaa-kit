#!/usr/bin/env python3
"""Source-pinned official IDL + authored ICD -> Cyclone native descriptor registry.

The generated C glue references idlc TypeSupport symbols but NEVER implements
payload serialization or claims native Provider/Consumer readiness.
Original licensed IDL/C generated by idlc stays in a private build tree.
"""
from __future__ import annotations
import argparse
import json
from pathlib import Path
import re
import shutil
import sys
import tempfile
from typing import Iterable

from tools.official_icd_evidence import audit, SourceError
from tools.official_idl_compile import collect
from tools.umaa_contract_ir import load_service

SHA = re.compile(r"[a-f0-9]{64}\Z")
IDENT = re.compile(r"[A-Za-z_]\w*\Z")
IDL = re.compile(r"UMAA(?:::[A-Za-z_]\w*){2,7}\Z")

HEADER = """/* GENERATED for a private Cyclone idlc build. NOT a payload codec.
 * Type descriptor identity is only one precondition for UMAA conformance. */
#pragma once
#include <dds/dds.h>
#include <stddef.h>
#ifdef __cplusplus
extern "C" {
#endif
typedef struct UmaaNativeTypeEvidenceV1 {
  const char *service_id;
  const char *idl_type;
  const char *dds_topic_name;
  const char *key_fields;
  const char *source_idl_sha256;
  const dds_topic_descriptor_t *descriptor;
} UmaaNativeTypeEvidenceV1;
size_t umaa_native_type_count(void);
const UmaaNativeTypeEvidenceV1 *umaa_native_type_at(size_t index);
const UmaaNativeTypeEvidenceV1 *umaa_native_type_lookup(const char *idl_type);
#ifdef __cplusplus
}
#endif
"""


def quote(text: str) -> str:
    return json.dumps(text, ensure_ascii=True)


def generate(archive: Path, yaml_paths: Iterable[Path], output: Path,
             expected_sha: str, original_root: Path | None = None) -> dict:
    service_paths = list(yaml_paths)
    if not SHA.fullmatch(expected_sha):
        raise SourceError("explicit 64-digit SHA-256 of external official IDL required")
    if not service_paths:
        raise SourceError("no Service YAML files supplied")
    if output.exists() or output.is_symlink() or any(p.is_symlink() for p in output.parents):
        raise SourceError("output directory must not already exist or be symlinked")
    evidence = audit(archive, service_paths)
    if evidence["archiveSha256"] != expected_sha:
        raise SourceError("external archive does not match supplied SHA-256")
    if evidence["issues"]:
        raise SourceError("source/YAML disagreement: " + "; ".join(evidence["issues"]))
    by_type: dict[str, dict] = {}
    sources = set()
    for path, entry in zip(service_paths, evidence["services"]):
        service_doc, _ = load_service(path)
        if service_doc["sources"]["idl"]["bundleSha256"] != expected_sha:
            raise SourceError("unreviewed or unpinned Service IDL bundle: " + entry["serviceId"])
        records = entry["topics"] + [{"alias": "embedded-collection",
                     "source": row} for row in entry["unresolvedCollectionTypes"]]
        for item in records:
            info = item["source"]
            fq = info["idlType"]
            if not IDL.fullmatch(fq) or not all(IDENT.fullmatch(p) for p in fq.split("::")):
                raise SourceError("unsafe TypeSupport identifier")
            if item["alias"] != "embedded-collection":
                doc_topic = service_doc["spec"]["topics"][item["alias"]]
                if doc_topic["ddsTopicName"] != info["ddsTopicName"] or doc_topic["keyFields"] != info["keyFields"]:
                    raise SourceError("Topic/Key not source-backed: " + fq)
            if fq in by_type:
                if by_type[fq]["source"] != info:
                    raise SourceError("conflicting duplicate TypeSupport: " + fq)
                continue
            by_type[fq] = {"serviceId": entry["serviceId"], "source": info}
            sources.add(info["idlPath"])
    if not by_type:
        raise SourceError("no native TypeSupport bindings")
    includes = sorted({data["source"]["idlPath"][:-4] + ".h" for data in by_type.values()})
    bindings = sorted(by_type.items())
    code = ['/* GENERATED from verified external IDL; no licensed source copied. */',
            '#include "umaa_native_type_registry.h"', '#include <string.h>']
    code.extend('#include ' + quote(p) for p in includes)
    code.append('static const UmaaNativeTypeEvidenceV1 types[] = {')
    for fq, data in bindings:
        typ=data["source"]
        symbol=fq.replace("::", "_") + "_desc"
        keys=",".join(typ["keyFields"])
        code.append("  {" + ", ".join([quote(data["serviceId"]), quote(fq),
            quote(typ["ddsTopicName"]), quote(keys), quote(typ["idlSha256"]),
            "&" + symbol]) + "},")
    code += ['};',
        'size_t umaa_native_type_count(void) { return sizeof(types)/sizeof(types[0]); }',
        'const UmaaNativeTypeEvidenceV1 *umaa_native_type_at(size_t index) {',
        '  return index < umaa_native_type_count() ? &types[index] : NULL;',
        '}',
        'const UmaaNativeTypeEvidenceV1 *umaa_native_type_lookup(const char *name) {',
        '  if (!name) return NULL;',
        '  for (size_t i = 0; i < umaa_native_type_count(); ++i)',
        '    if (strcmp(name, types[i].idl_type)==0) return &types[i];',
        '  return NULL;',
        '}', '']
    smoke = ['/* Generated native-descriptor linkage smoke, NOT a wire codec test. */',
        '#include "umaa_native_type_registry.h"', '#include <string.h>',
        'int main(void) {',
        f'  if(umaa_native_type_count()!={len(bindings)}) return 2;',
        '  if(umaa_native_type_at(umaa_native_type_count())!=NULL) return 3;',
        '  if(umaa_native_type_lookup("UMAA::NotAType")!=NULL) return 4;',
        '  for(size_t i=0;i<umaa_native_type_count();i++){',
        '    const UmaaNativeTypeEvidenceV1 *entry=umaa_native_type_at(i);',
        '    if(!entry || !entry->descriptor || !entry->source_idl_sha256',
        '       || strcmp(entry->dds_topic_name,entry->idl_type)) return 5;',
        '    if(umaa_native_type_lookup(entry->idl_type)!=entry) return 6;',
        '  }',
        '  return 0;',
        '}', '']
    deps = set(sources)
    if original_root is not None:
        root = original_root.resolve()
        for source in sorted(sources):
            for p in collect(root, root / source):
                deps.add(p.relative_to(root).as_posix())
    summary = {
        "kind": "EXTERNAL_OFFICIAL_CYCLONE_DESCRIPTOR_REGISTRY",
        "sourceArchiveSha256": expected_sha,
        "sourceEvidenceServices": evidence["servicesAudited"],
        "sourceEvidenceTopics": evidence["topicsAudited"],
        "nativeDescriptorCount": len(bindings),
        "nativeIdlFiles": sorted(deps),
        "descriptorNames": [fq for fq, _ in bindings],
        "qosApproved": False,
        "operationsApproved": False,
        "payloadCodecGenerated": False,
        "runtimeWireConformanceVerified": False,
        "disclaimer": "Native descriptor linkage only, not a full UMAA Component",
    }
    output.parent.mkdir(parents=True, exist_ok=True)
    stage = Path(tempfile.mkdtemp(prefix=".native-verified-", dir=output.parent))
    try:
        (stage / "umaa_native_type_registry.h").write_text(HEADER, encoding="utf-8")
        (stage / "umaa_native_type_registry.c").write_text("\n".join(code), encoding="utf-8")
        (stage / "native_descriptor_smoke.c").write_text("\n".join(smoke), encoding="utf-8")
        (stage / "native_manifest.json").write_text(
            json.dumps(summary, indent=2, sort_keys=True) + "\n", encoding="utf-8")
        stage.rename(output)
        return summary
    finally:
        if stage.exists():
            shutil.rmtree(stage)


def main(argv=None) -> int:
    p=argparse.ArgumentParser(description="Generate source-verified native Cyclone descriptor registry")
    p.add_argument("--zip", type=Path, required=True)
    p.add_argument("--yaml-root", type=Path, required=True)
    p.add_argument("--original-idl-root", type=Path)
    p.add_argument("--out", type=Path, required=True)
    p.add_argument("--expect-sha256", required=True)
    args=p.parse_args(argv)
    try:
        docs=sorted((args.yaml_root / "services").glob("*/*.yaml"))
        summary=generate(args.zip,docs,args.out,args.expect_sha256,args.original_idl_root)
        print("UMAA_OFFICIAL_NATIVE_REGISTRY_GENERATED",
              summary["nativeDescriptorCount"],"descriptors;",
              summary["sourceEvidenceServices"],"Services")
        return 0
    except (OSError,SourceError,ValueError) as e:
        print("UMAA_NATIVE_BINDING_ERROR: " + str(e),file=sys.stderr)
        return 2


if __name__=="__main__":
    raise SystemExit(main())
