#!/usr/bin/env python3
"""ICD YAML + source-pinned native DDS TypeSupport build, independent of vendors.

This deliberately does not manufacture UMAA Component providers from unknown
Key/QoS/codec mappings. It emits verified assembly metadata, native vendor
TypeSupport build targets and C++ topic contract descriptors, not official
service conformance. Unsupported bindings fail closed.
"""
from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path
import re
import sys
from zipfile import BadZipFile, ZipFile

from tools.native_dds_codegen import native_generate
from tools.official_idl_compile import collect
from tools.native_dds_backends import load as load_compiler_plugin
from tools.umaa_contract_ir import load_service, resolve_native, ContractIRError
from tools.umaa_component_cli import validate as validate_component
from tools.validate_icd_yaml import ICDYamlError

MARK = "// GENERATED by native_component_codegen.py; DO NOT EDIT\n"
CMAKE_MARK = "# GENERATED by native_component_codegen.py; DO NOT EDIT\n"
CPP_FQN = re.compile(r"^[A-Za-z_]\w*(?:::[A-Za-z_]\w*)+$")
SAFE_TOPIC = re.compile(r"^[A-Za-z_]\w*$")
SAFE_PATH = re.compile(r"^[A-Za-z0-9_./-]+$")


def _hash(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def _write(path: Path, body: str, marker: str = MARK):
    if path.is_symlink() or any(p.is_symlink() for p in path.parents):
        raise ContractIRError("symlinked native Component output forbidden")
    if path.exists() and not path.read_text(encoding="utf-8").startswith(marker):
        raise ContractIRError("refuse replacing user-owned output: " + str(path))
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(marker + body, encoding="utf-8")


def _cxx(value: str) -> str:
    return json.dumps(value, ensure_ascii=True)


def _identifier(value: str) -> str:
    result = value.replace("::", "_")
    if not SAFE_TOPIC.fullmatch(result):
        raise ContractIRError("unsafe generated service identifier")
    return result


def _binding_map(items: list[str]) -> dict[str, str]:
    result = {}
    for item in items:
        typename, found, source = item.partition("=")
        if (not found or not CPP_FQN.fullmatch(typename) or
                not SAFE_PATH.fullmatch(source) or
                Path(source).is_absolute() or ".." in Path(source).parts or
                not source.endswith(".idl") or typename in result):
            raise ContractIRError("expected unique --idl-binding Type::Name=relative.idl")
        result[typename] = source
    return result


def generate(manifest: Path, yaml_paths: list[Path], idl_root: Path,
             idl_bindings: dict[str, str], output: Path, *,
             backends: list[str] | None = None, fixture: bool = False,
             original_icd: Path | None = None,
             idl_archive: Path | None = None,
             runtime_report: dict | None = None) -> dict:
    if not yaml_paths or output.is_symlink():
        raise ContractIRError("missing Service YAML or symlinked output")
    doc = validate_component(json.loads(manifest.read_text(encoding="utf-8")),
                             nonempty=True)
    services = [load_service(p) for p in yaml_paths]
    items = {s["metadata"]["id"]: (s, digest) for s, digest in services}
    if len(items) != len(services):
        raise ContractIRError("duplicate Service ICD YAML")
    if {x["id"] for x in doc["services"]} != set(items):
        raise ContractIRError("Component assembly and Service YAML differ")
    # Every selected DDS Topic must have an EXPLICIT source, not a guessed
    # basename derived from its spelling. Supports Collections and arbitrary
    # IDL grammar because no Python IDL parser is invoked here.
    expected = {}
    for service_id, (service, _) in items.items():
        is_demo = service_id.startswith("Demo::")
        if fixture != is_demo:
            raise ContractIRError("Demo:: requires --fixture; official service forbids it")
        source = service["sources"]["icd"]
        pinned = service["sources"]["idl"]["bundleSha256"]
        if not pinned:
            raise ContractIRError(service_id + ": IDL SHA-256 source pin required")
        if not fixture:
            if (original_icd is None or not original_icd.is_file() or
                original_icd.is_symlink() or _hash(original_icd.read_bytes()) !=
                    source["originalSha256"] or
                source["reference"]["kind"] != "official"):
                raise ContractIRError(service_id + ": authoritative original ICD not verified")
            checks = service["verification"]
            if not checks["officialIdlVerified"] or not checks["ddsQosVerified"]:
                raise ContractIRError(service_id + ": official IDL/QoS not reviewed")
            if (idl_archive is None or not idl_archive.is_file() or
                idl_archive.is_symlink() or _hash(idl_archive.read_bytes()) != pinned):
                raise ContractIRError(service_id + ": official IDL bundle SHA invalid")
        for alias, topic in service["spec"]["topics"].items():
            typename = topic["idlType"]
            if typename not in idl_bindings:
                raise ContractIRError("missing explicit native IDL type-to-file binding: " + typename)
            if not topic["ddsTopicName"] or not topic["qosProfileRef"]:
                raise ContractIRError("unresolved DDS Topic or QoS: " + service_id + "/" + alias)
            if not isinstance(topic["keyFields"], list):
                raise ContractIRError("unresolved Key field declaration")
            expected[typename] = idl_bindings[typename]
        for operation, value in service["spec"]["operations"].items():
            if (value["kind"] == "unresolved" or value["topicRef"] is None or
                value["sourceClause"] not in source["clauses"]):
                raise ContractIRError(service_id + ": unresolved Operation " + operation)
    if set(idl_bindings) != set(expected):
        raise ContractIRError("unreferenced TypeSupport bindings prohibited")
    # A native Runtime Adapter needs explicit service, Key, field, schema,
    # Topic and QoS mapping. Never infer these from compiled TypeSupport.
    # This first slice permits ONLY the synthetic BatteryStatus fixture.
    runtime_binding = None
    if runtime_report is not None:
        if not fixture or len(items) != 1 or set(runtime_report) != {
            "typeName", "keyField", "valueField", "schemaId"
        }:
            raise ContractIRError("runtime Report requires one synthetic fixture and complete codec")
        service_id, (service, _) = next(iter(items.items()))
        reports = [topic for topic in service["spec"]["topics"].values()
                   if topic["role"] == "report"]
        if (service_id != "Demo::EO::BatteryStatus" or
            len(service["spec"]["topics"]) != 1 or len(reports) != 1):
            raise ContractIRError("only reviewed synthetic BatteryStatus Report may bind")
        topic = reports[0]
        if (runtime_report["typeName"] != topic["idlType"] or
            topic["keyFields"] != [runtime_report["keyField"]] or
            topic["direction"] != "provider-to-consumer" or
            not runtime_report["schemaId"]):
            raise ContractIRError("runtime codec or Key differs from explicit ICD Topic")
        runtime_binding = {
            "typeName": runtime_report["typeName"],
            "idlSource": expected[topic["idlType"]],
            "keyField": runtime_report["keyField"],
            "valueField": runtime_report["valueField"],
            "schemaId": runtime_report["schemaId"],
            "topicName": topic["ddsTopicName"],
            "qosProfile": topic["qosProfileRef"],
            "serviceId": service_id,
        }

    if fixture:
        # Legacy synthetic fixture pins a single IDL file, not an archive.
        pins = {s["sources"]["idl"]["bundleSha256"] for s, _ in services}
        unique_sources = set(expected.values())
        if len(pins) != 1 or len(unique_sources) != 1:
            raise ContractIRError("synthetic fixture requires one pinned IDL source")
        candidate = idl_root / next(iter(unique_sources))
        if not candidate.is_file() or candidate.is_symlink() or _hash(candidate.read_bytes()) not in pins:
            raise ContractIRError("synthetic IDL source SHA mismatch")
    # Validate all inputs and existing user-owned files before invoking
    # expensive native compilers. Generated output is explicitly TypeSupport
    # metadata, never a fabricated live UMAA provider or DDS backend.
    root = idl_root.resolve(strict=True)
    if not root.is_dir():
        raise ContractIRError("IDL root must be a directory")
    output = output.resolve()
    if root == output or root in output.parents:
        raise ContractIRError("generated project must be outside source IDL root")
    if not fixture:
        # An independently supplied archive digest alone does not prove that
        # a mutable extracted tree contains the SAME bytes. Authenticate all
        # selected transitive IDL inputs directly against the pinned ZIP.
        try:
            with ZipFile(idl_archive) as original:
                members = original.namelist()
                if len(members) != len(set(members)):
                    raise ContractIRError("duplicate official IDL ZIP entries")
                for rel in sorted(set(expected.values())):
                    for dep in collect(root, root / rel):
                        entry = dep.relative_to(root).as_posix()
                        if dep.stat().st_size > 4_000_000:
                            raise ContractIRError("official IDL dependency too large")
                        if original.read(entry) != dep.read_bytes():
                            raise ContractIRError("extracted official IDL bytes differ from pinned ZIP: " + entry)
        except (BadZipFile, KeyError) as exc:
            raise ContractIRError("official IDL archive missing required source dependency") from exc
    targets = []
    source_results = []
    for rel in sorted(set(expected.values())):
        if not SAFE_PATH.fullmatch(rel) or Path(rel).is_absolute() or ".." in Path(rel).parts:
            raise ContractIRError("unsafe IDL binding source")
        dest = output / "generated/native" / _hash(rel.encode())[:16]
        result = native_generate(root, rel, dest, backends=backends)
        source_results.append(result)
        targets.extend(result["nativeTargets"])
    if len(set(targets)) != len(targets):
        # Every subgraph gets a CMake namespace; nonunique compiled target
        # names are not silently combined across IDL source closures.
        pass  # names are rewritten in child fragments below
    # Include child fragments in independent CMake scopes, namespaced by a
    # path-derived ID so two separately compiled official types can coexist.
    # Each child is generated by native_dds_codegen, never this ICD module.
    includes = []
    for result in source_results:
        rel = _hash(result["source"].encode())[:16]
        original = output / "generated/native" / rel / "native-targets.cmake"
        script = original.read_text(encoding="utf-8")
        # Avoid duplicate global target identifiers when several types
        # generate different dependency closures.
        renamed = []
        for backend in result["backends"]:
            old = "umaa_native_" + backend + "_types"
            new = "umaa_native_" + rel + "_" + backend + "_types"
            script = script.replace(old, new)
            renamed.append(new)
        _write(output / "generated" / ("native_" + rel + ".cmake"), script, CMAKE_MARK)
        includes.append(("generated/native_" + rel + ".cmake", renamed))
    # Verify exact native C/C++ type names and key MEMBER presence by
    # compiling provider-owned probes. This intentionally does not claim
    # that a field was annotated @key in the original source, nor that QoS
    # or host-native payload conversion has been reviewed.
    probe_jobs = []
    by_source = {result["source"]: result for result in source_results}
    for typename, rel_source in sorted(expected.items()):
        result = by_source[rel_source]
        idlh = _hash(rel_source.encode())[:16]
        typeh = _hash(typename.encode())[:12]
        for backend in result["backends"]:
            plugin = load_compiler_plugin(backend)
            if not callable(getattr(plugin, "type_probe", None)):
                raise ContractIRError("compiler backend lacks type_probe: " + backend)
            keys = sorted({field for service, _ in services
                           for topic in service["spec"]["topics"].values()
                           if topic["idlType"] == typename
                           for field in topic["keyFields"]})
            probe = plugin.type_probe(typename, rel_source, keys)
            if (not isinstance(probe, dict) or
                set(probe) != {"language", "extension", "code"} or
                probe["language"] not in ("C", "CXX") or
                probe["extension"] not in (".c", ".cpp") or
                not isinstance(probe["code"], str) or not probe["code"]):
                raise ContractIRError("invalid provider native type probe")
            stem = "native_probe_" + idlh + "_" + typeh + "_" + backend
            filename = "tests/" + stem + probe["extension"]
            _write(output / filename, probe["code"])
            probe_includes = ["generated/native/" + idlh + "/" + backend + "/" + folder
                              for folder in result["nativeBuildSpecifications"][backend]["includeDirs"]]
            probe_jobs.append((stem, filename, probe["language"], probe_includes))
    descriptors = ["#pragma once", "#include <cstddef>", "namespace umaa_native_contract {",
                   "struct Topic {const char* alias;const char* name;const char* idlType;"
                   "const char* keyFields;const char* qos;};"]
    for service_id, (service, _) in sorted(items.items()):
        name = _identifier(service_id)
        descriptors.append("struct " + name + " {")
        descriptors.append("  static constexpr const char* id = " + _cxx(service_id) + ";")
        descriptors.append("  static constexpr bool runtime_binding_verified = false;")
        topics = sorted(service["spec"]["topics"].items())
        descriptors.append("  static constexpr Topic topics[] = {")
        for alias, topic in topics:
            fields = ",".join(topic["keyFields"])
            descriptors.append("    {" + ",".join(_cxx(x) for x in
                  (alias, topic["ddsTopicName"], topic["idlType"], fields,
                   topic["qosProfileRef"])) + "},")
        descriptors.append("  };")
        descriptors.append("  static constexpr std::size_t topicCount = " +
                           str(len(topics)) + ";")
        descriptors.append("};")
    descriptors.append("} // namespace umaa_native_contract")
    _write(output / "generated/native_service_contracts.hpp",
           "\n".join(descriptors) + "\n")
    names = [_identifier(x) for x in sorted(items)]
    _write(output / "tests/native_contract_smoke.cpp",
           '#include "generated/native_service_contracts.hpp"\n'
           'int main(){\n' +
           "\n".join("  if(umaa_native_contract::" + name +
                     "::runtime_binding_verified || !umaa_native_contract::" +
                     name + "::topicCount)return 4;" for name in names) +
           "\n  return 0;\n}\n")
    _write(output / "tests/native_loader_smoke.cpp",
           '#include <iostream>\n#if defined(_WIN32)\n#include <windows.h>\n'
           'int main(int n,char** a){if(n<2)return 2;'
           'for(int i=1;i<n;++i){auto p=LoadLibraryA(a[i]);'
           'if(!p)return 3;FreeLibrary(p);}return 0;}\n'
           '#else\n#include <dlfcn.h>\n'
           'int main(int n,char** a){if(n<2)return 2;'
           'for(int i=1;i<n;++i){void* p=dlopen(a[i],RTLD_NOW|RTLD_LOCAL);'
           'if(!p){std::cerr<<dlerror();return 3;}dlclose(p);}return 0;}\n'
           '#endif\n')
    d = "$"
    cmake = ["cmake_minimum_required(VERSION 3.20)",
             "project(UMAAICDNativeTypeSupport LANGUAGES C CXX)",
             "enable_testing()",
             "set(UMAA_NATIVE_COMPONENT_TARGETS \"\")"]
    for cmake_path, _ in includes:
        cmake += ["include(\"" + d + "{CMAKE_CURRENT_SOURCE_DIR}/" + cmake_path + "\")",
                  "list(APPEND UMAA_NATIVE_COMPONENT_TARGETS " + d + "{UMAA_NATIVE_TARGETS})"]
    for stem, filename, language, dirs in probe_jobs:
        cmake.append("add_library(" + stem + " OBJECT " + filename + ")")
        cmake.append("target_include_directories(" + stem + " PRIVATE " +
                     " ".join('"' + d + "{CMAKE_CURRENT_SOURCE_DIR}/" + v + '"'
                              for v in dirs) + ")")
        if language == "CXX":
            cmake.append("target_compile_features(" + stem +
                         " PRIVATE cxx_std_17)")
        else:
            cmake.append("set_target_properties(" + stem +
                         " PROPERTIES C_STANDARD 11)")
    cmake += [
        "add_executable(umaa_native_contract_smoke tests/native_contract_smoke.cpp)",
        "target_compile_features(umaa_native_contract_smoke PRIVATE cxx_std_17)",
        "target_include_directories(umaa_native_contract_smoke PRIVATE " +
        d + "{CMAKE_CURRENT_SOURCE_DIR})",
        "add_test(NAME umaa_native_contract_smoke COMMAND umaa_native_contract_smoke)",
        "add_executable(umaa_native_libraries_smoke tests/native_loader_smoke.cpp)",
        "target_link_libraries(umaa_native_libraries_smoke PRIVATE " + d + "{CMAKE_DL_LIBS})",
        "set(UMAA_DLL_PATHS \"\")",
        "foreach(target IN LISTS UMAA_NATIVE_COMPONENT_TARGETS)",
        "  list(APPEND UMAA_DLL_PATHS \"$<TARGET_FILE:" + d + "{target}>\")",
        "endforeach()",
        "add_test(NAME umaa_native_compiler_libraries_smoke",
        " COMMAND umaa_native_libraries_smoke " + d + "{UMAA_DLL_PATHS})",
    ]
    _write(output / "CMakeLists.txt", "\n".join(cmake) + "\n", CMAKE_MARK)
    summary = {
        "generatedBy": "native_component_codegen.py",
        "componentId": doc["component"]["id"],
        "services": sorted(items),
        "nativeCompilerBackends": source_results[0]["backends"] if source_results else [],
        "nativeIdlSources": sorted(set(expected.values())),
        "nativeTypeSupportGenerated": True,
        "nativeTypeProbesGenerated": len(probe_jobs),
        "contractIR": {
            load_service(path)[0]["metadata"]["id"]:
                resolve_native(path, type_sources=expected,
                               generated_sources=by_source, fixture=fixture)
            for path in yaml_paths
        },
        "nativeDdsBinding": False,
        "componentRuntimeBound": False,
        "officialConformanceClaim": False,
        "blockers": [
            "Native DDS TypeSupport is generated; vendor-neutral host/native payload adapter not proven",
            "Original native TypeSupport Key/QoS semantics are not established by compilation",
            "Component runtime Provider/Consumer registration cannot be emitted safely without reviewed wire codecs",
        ],
    }
    metadata = output / "generated/native-generation.json"
    if metadata.is_symlink() or any(p.is_symlink() for p in metadata.parents):
        raise ContractIRError("unsafe native metadata destination")
    if metadata.exists():
        previous = json.loads(metadata.read_text(encoding="utf-8"))
        if previous.get("generatedBy") != "native_component_codegen.py":
            raise ContractIRError("refusing to replace user-owned native metadata")
    metadata.write_text(json.dumps(summary, indent=2, sort_keys=True) + "\n",
                        encoding="utf-8")
    return summary


def main(argv=None):
    p = argparse.ArgumentParser(description="backend-independent ICD native TypeSupport project")
    p.add_argument("--manifest", required=True, type=Path)
    p.add_argument("--yaml", required=True, action="append", type=Path)
    p.add_argument("--idl-root", required=True, type=Path)
    p.add_argument("--idl-binding", required=True, action="append")
    p.add_argument("--backend", action="append")
    p.add_argument("--out", required=True, type=Path)
    p.add_argument("--fixture", action="store_true")
    p.add_argument("--original-icd", type=Path)
    p.add_argument("--idl-archive", type=Path)
    args = p.parse_args(argv)
    try:
        result = generate(args.manifest, args.yaml, args.idl_root,
                          _binding_map(args.idl_binding), args.out,
                          backends=args.backend, fixture=args.fixture,
                          original_icd=args.original_icd,
                          idl_archive=args.idl_archive)
        print("UMAA_ICD_NATIVE_PROJECT_GENERATED", json.dumps(result, sort_keys=True))
        return 0
    except (OSError, ValueError, ICDYamlError) as exc:
        print("UMAA_ICD_NATIVE_GENERATOR_ERROR:", str(exc), file=sys.stderr)
        return 2


if __name__ == "__main__":
    raise SystemExit(main())
