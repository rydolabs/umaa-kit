"""Trusted source template substitution shared by native runtime adapter plugins.

Never parses IDL or writes CDR. The native vendor compiler owns TypeSupport.
The template is a reviewed vendor adapter implementing the stable DDS C ABI.
Only explicitly pinned, schema-checked scalar Report bindings can invoke it.
"""
from __future__ import annotations

from pathlib import Path
import re

_ID = re.compile(r"^[A-Za-z_]\w*$")
_FQN = re.compile(r"^[A-Za-z_]\w*(?:::[A-Za-z_]\w*)+$")
_TOKEN = re.compile(r"^[A-Za-z0-9_./:+-]{1,240}$")


def validate(binding: dict) -> dict:
    exact = {"typeName", "idlSource", "keyField", "valueField",
             "topicName", "schemaId", "qosProfile", "serviceId"}
    if not isinstance(binding, dict) or set(binding) != exact:
        raise ValueError("native Report runtime binding missing explicit fields")
    if not _FQN.fullmatch(binding["typeName"]) or not _FQN.fullmatch(binding["serviceId"]):
        raise ValueError("unsafe fully qualified native Report type or service")
    for name in ("keyField", "valueField"):
        if not _ID.fullmatch(binding[name]):
            raise ValueError("unsafe native Report member name")
    if binding["keyField"] == binding["valueField"]:
        raise ValueError("Report key/value fields must be different")
    if not _TOKEN.fullmatch(binding["topicName"]) or not _TOKEN.fullmatch(binding["schemaId"]):
        raise ValueError("unsafe Topic or schema binding")
    if not _TOKEN.fullmatch(binding["qosProfile"]):
        raise ValueError("unsafe QoS profile binding")
    source = Path(binding["idlSource"])
    if (source.is_absolute() or source.suffix != ".idl" or
        ".." in source.parts or not source.stem.isidentifier()):
        raise ValueError("unsafe native IDL header mapping")
    return binding


def render(reference: Path, binding: dict, *, language: str) -> str:
    binding = validate(binding)
    if language not in ("cyclone", "fastdds"):
        raise ValueError("unregistered runtime adapter template")
    text = reference.read_text(encoding="utf-8")
    original = "Demo::EO::BatteryReportType"
    old_c = original.replace("::", "_")
    native = binding["typeName"]
    raw_type = native.replace("::", "_")
    header = Path(binding["idlSource"]).stem
    # The trusted reference C ABI adapter already implements discovery,
    # independent Writer/Reader, sample lifecycle, strict unknown schema,
    # QoS capabilities, ACK and error handling.
    substitutions = [
        ("DemoBatteryPubSubTypes.h", header + "PubSubTypes.h"),
        ("DemoBattery.h", header + ".h"),
        (original, native),
        (old_c, raw_type),
        ("demo/BatteryStatus", binding["topicName"]),
        ("demo:battery-v1", binding["schemaId"]),
        ("demo-reliable", binding["qosProfile"]),
        ("source_id", binding["keyField"]),
        ("level_percent", binding["valueField"]),
    ]
    for old, new in substitutions:
        if old == new:
            continue
        if old not in text:
            raise ValueError("trusted native Report adapter template changed: " + old)
        text = text.replace(old, new)
    if language == "cyclone":
        assertion = ('static_assert(sizeof(((' + raw_type + '*)nullptr)->' +
                     binding["keyField"] + ') == sizeof(int32_t), ' +
                     '"native Report key must be int32");\n' +
                     'static_assert(sizeof(((' + raw_type + '*)nullptr)->' +
                     binding["valueField"] + ') == sizeof(int32_t), ' +
                     '"native Report scalar value must be int32");\n')
    else:
        assertion = (
            '#include <type_traits>\n#include <utility>\n'
            'static_assert(std::is_same_v<std::decay_t<decltype('
            'std::declval<' + native + '&>().' + binding["keyField"] +
            '())>, int32_t>, "native key must be int32");\n'
            'static_assert(std::is_same_v<std::decay_t<decltype('
            'std::declval<' + native + '&>().' + binding["valueField"] +
            '())>, int32_t>, "native Report value must be int32");\n'
        )
    anchor = "namespace {\n"
    if text.count(anchor) != 1:
        raise ValueError("native vendor reference ABI entrypoint changed")
    text = text.replace(anchor, assertion + anchor, 1)
    return ('// GENERATED by native backend-owned report adapter. SYNTHETIC\n'
            '// Original vendor TypeSupport is emitted by idlc/fastddsgen;\n'
            '// runtime binding is explicitly reviewed fixture-only.\n'
            + text)
