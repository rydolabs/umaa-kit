#!/usr/bin/env python3
"""Backend-independent native DDS compiler orchestration.

No IDL grammar parser and no vendor-specific code in this module. Each
trusted provider module in tools.native_dds_backends owns compiler invocation,
native artifacts and CMake link requirements. Adding another backend changes
only the installed provider module, not the orchestrator/CLI/CMake consumers.
"""
from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path
import re
import subprocess
import sys

from tools.native_dds_backends import discover, load
from tools.official_idl_compile import collect

_SAFE_ID = re.compile(r"^[a-z][a-z0-9_]{0,39}$")
_SAFE_CMAKE = re.compile(r"^[A-Za-z0-9_:.+=/ -]+$")


def sha256(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def _quote(value: str) -> str:
    if not isinstance(value, str) or not _SAFE_CMAKE.fullmatch(value):
        raise ValueError("unsafe CMake build token from DDS backend")
    return '"' + value + '"'


def _validate_build(name: str, payload: dict, folder: Path) -> dict:
    required = ("sources", "includeDirs", "language", "cmakePackages",
                "cmakeLibraries", "cmakeFeatures", "cmakeProperties")
    if not isinstance(payload, dict) or set(payload) != set(required):
        raise ValueError("backend did not return a complete build contract")
    if payload["language"] not in ("C", "CXX"):
        raise ValueError("unsupported backend native source language")
    if not payload["sources"]:
        raise ValueError("backend returned empty native TypeSupport")
    for item in payload["sources"]:
        p = folder / item
        if (not isinstance(item, str) or Path(item).is_absolute() or
            not p.resolve().is_relative_to(folder.resolve()) or
            not p.is_file() or p.is_symlink()):
            raise ValueError("backend emitted unsafe/missing native file")
    for item in payload["includeDirs"]:
        p = folder / item
        if (not isinstance(item, str) or Path(item).is_absolute() or
            not p.resolve().is_relative_to(folder.resolve()) or
            not p.is_dir()):
            raise ValueError("backend returned unsafe generated include directory")
    for k in ("cmakePackages", "cmakeLibraries", "cmakeFeatures"):
        if not isinstance(payload[k], list) or any(not isinstance(x, str) or
                not _SAFE_CMAKE.fullmatch(x) for x in payload[k]):
            raise ValueError("unsafe backend CMake metadata")
    props = payload["cmakeProperties"]
    if not isinstance(props, dict) or any(
        not _SAFE_CMAKE.fullmatch(k) or not isinstance(v, str) or
        not _SAFE_CMAKE.fullmatch(v) for k, v in props.items()
    ):
        raise ValueError("unsafe backend CMake target property")
    return payload


def render_cmake(root: Path, specifications: dict[str, dict]) -> str:
    lines = [
        "# Generated by backend-independent native_dds_codegen.py",
        "# Source TypeSupport was emitted by real vendor compilers.",
        "set(UMAA_NATIVE_TARGETS \"\")",
    ]
    for name, spec in sorted(specifications.items()):
        if not _SAFE_ID.fullmatch(name):
            raise ValueError("unsafe backend name")
        target = "umaa_native_" + name + "_types"
        folder = root / name
        for package in spec["cmakePackages"]:
            lines.append("find_package(" + package + ")")
        sources = [_quote(str(folder / path)) for path in spec["sources"]]
        lines.append("add_library(" + target + " SHARED " + " ".join(sources) + ")")
        includes = [_quote(str(folder / path)) for path in spec["includeDirs"]]
        if includes:
            lines.append("target_include_directories(" + target +
                         " PRIVATE " + " ".join(includes) + ")")
        if spec["cmakeLibraries"]:
            lines.append("target_link_libraries(" + target + " PRIVATE " +
                         " ".join(spec["cmakeLibraries"]) + ")")
        if spec["cmakeFeatures"]:
            lines.append("target_compile_features(" + target + " PRIVATE " +
                         " ".join(spec["cmakeFeatures"]) + ")")
        if spec["cmakeProperties"]:
            properties = " ".join(k + " " + v for k, v in spec["cmakeProperties"].items())
            lines.append("set_target_properties(" + target +
                         " PROPERTIES " + properties + ")")
        lines.extend([
            "if(UNIX AND NOT APPLE)",
            "  target_link_options(" + target + " PRIVATE \"LINKER:--no-undefined\")",
            "endif()",
            "list(APPEND UMAA_NATIVE_TARGETS " + target + ")",
        ])
    lines.append("")
    return "\n".join(lines)


def native_generate(root: Path, source: str, output: Path, *,
                    vendor: str = "all",
                    backends: list[str] | tuple[str, ...] | None = None,
                    backend_tools: dict[str, str] | None = None,
                    source_sha256: str | None = None) -> dict:
    root = root.resolve(strict=True)
    if not root.is_dir() or output.is_symlink():
        raise ValueError("input root must be a directory and output cannot be a symlink")
    name = Path(source)
    if (name.is_absolute() or name.suffix.lower() != ".idl" or not name.parts
            or any(p in ("", ".", "..") for p in name.parts)):
        raise ValueError("IDL source must be a relative .idl path within its root")
    target = root / name
    if not target.is_file() or target.is_symlink():
        raise ValueError("IDL source is missing or a symlink")
    if output.resolve() == root or root in output.resolve().parents:
        raise ValueError("generated output must not be inside the original IDL tree")
    closure = collect(root, target)
    if not closure or any(p.is_symlink() for p in closure):
        raise ValueError("missing or unsafe IDL include dependency")
    digest = sha256(target)
    if source_sha256 is not None and digest != source_sha256:
        raise ValueError("source SHA-256 mismatch")
    if backends is None:
        # "both" is retained for backward-compatible CLIs; means all
        # installed compiler plugins, including future providers.
        backends = list(discover()) if vendor in ("both", "all") else [vendor]
    if not backends or len(set(backends)) != len(backends):
        raise ValueError("empty/duplicate native backend selection")
    plugins = {name: load(name) for name in backends}
    for name in plugins:
        if not _SAFE_ID.fullmatch(name):
            raise ValueError("unsafe DDS backend id")
    overrides = backend_tools or {}
    if set(overrides) - set(plugins):
        raise ValueError("native compiler override has no selected backend")
    output = output.resolve()
    # Validate prerequisites before creating any generated output directory.
    for name, plugin in plugins.items():
        if callable(getattr(plugin, "available", None)) and not plugin.available(
                executable=overrides.get(name)):
            raise FileNotFoundError("unavailable compiler backend: " + name)
    output.mkdir(parents=True, exist_ok=True)
    specifications = {}
    for name, plugin in plugins.items():
        folder = output / name
        folder.mkdir(parents=True, exist_ok=True)
        spec = plugin.generate(root, target, closure, folder,
                               executable=overrides.get(name))
        specifications[name] = _validate_build(name, spec, folder)
    result = {
        "format": "UMAA-native-IDL-generator-v2",
        "vendor": vendor,
        "backends": list(plugins),
        "source": Path(source).as_posix(),
        "inputSha256": digest,
        "transitiveIdls": len(closure),
        "sourceDependencies": [
            {"path": item.relative_to(root).as_posix(), "sha256": sha256(item)}
            for item in closure
        ],
        "nativeSources": {
            backend: [backend + "/" + path for path in spec["sources"]]
            for backend, spec in specifications.items()
        },
        "nativeTargets": ["umaa_native_" + backend + "_types" for backend in plugins],
        "nativeTypeSupportGenerated": True,
        "nativeDdsBinding": False,
        "serviceQosVerified": False,
        "officialConformanceClaim": False,
    }
    # Treat these as a transactional generation pair: metadata and CMake
    # are written only after every selected plugin reports valid artifacts.
    (output / "native-targets.cmake").write_text(
        render_cmake(output, specifications), encoding="utf-8")
    (output / "native-generation.json").write_text(
        json.dumps(result, indent=2, sort_keys=True) + "\n", encoding="utf-8")
    return result


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description="backend-neutral native IDL compiler pipeline")
    ap.add_argument("--root", type=Path, required=True)
    ap.add_argument("--source", required=True)
    ap.add_argument("--out", type=Path, required=True)
    ap.add_argument("--vendor", default="all", help="plugin ID or all (legacy both)")
    ap.add_argument("--backend", action="append",
                    help="installed compiler plugin ID; repeat to select several")
    ap.add_argument("--tool", action="append", default=[],
                    help="per-provider executable override, plugin_id=path")
    ap.add_argument("--source-sha256")
    args = ap.parse_args(argv)
    try:
        overrides = {}
        for token in args.tool:
            name, sep, path = token.partition("=")
            if not sep or not path or name in overrides:
                raise ValueError("invalid/duplicate --tool plugin_id=path")
            overrides[name] = path
        result = native_generate(args.root, args.source, args.out,
                                 vendor=args.vendor, backends=args.backend,
                                 backend_tools=overrides,
                                 source_sha256=args.source_sha256)
        print("UMAA_NATIVE_IDL_GENERATION_PASS",
              ",".join(result["backends"]),
              "dependencies=", result["transitiveIdls"],
              "native_sources=", sum(map(len, result["nativeSources"].values())))
        return 0
    except (OSError, ValueError, subprocess.CalledProcessError,
            subprocess.TimeoutExpired) as exc:
        print("UMAA_NATIVE_IDL_GENERATION_FAIL: " + str(exc), file=sys.stderr)
        return 2


if __name__ == "__main__":
    raise SystemExit(main())
