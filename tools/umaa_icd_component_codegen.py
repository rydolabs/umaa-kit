#!/usr/bin/env python3
"""Generate vendor-neutral C++ Component v2 scaffolds from resolved YAML+IDL.

Restricted first vertical slice: Report and Command *provider* ABI modules,
and typed consumer callback skeletons (not live DDS subscriptions).
Supports only scalar IDL "long" and "string" fields. Unsupported types fail.
No native DDS TypeSupport is produced or implied.
"""
from __future__ import annotations
import argparse
import json
from pathlib import Path
import re
import sys

from sdk.tools.umaa_codegen import parse_idl, render_types
from tools import umaa_component_cli as cli
from tools.umaa_contract_ir import resolve, ContractIRError

MARK = "// GENERATED by umaa_icd_component_codegen.py; DO NOT EDIT\n"
CMAKE_MARK = "# GENERATED by umaa_icd_component_codegen.py; DO NOT EDIT\n"
MAX_STRING = 1_048_576


def cpp_literal(value: str) -> str:
    return json.dumps(value, ensure_ascii=True)


def identifier(name: str) -> str:
    value = name.replace("::", "_")
    if not re.fullmatch(r"[A-Za-z_]\w*", value):
        raise ContractIRError("unsafe C++ identifier")
    return value


def write_generated(path: Path, body: str, mark: str = MARK) -> None:
    if path.is_symlink() or any(parent.is_symlink() for parent in path.parents):
        raise ContractIRError("refusing symlink output: " + str(path))
    if path.exists() and not path.read_text(encoding="utf-8").startswith(mark):
        raise ContractIRError("refusing to overwrite user-owned file: " + str(path))
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(mark + body, encoding="utf-8")


def write_user(path: Path, body: str) -> None:
    if path.is_symlink() or any(parent.is_symlink() for parent in path.parents):
        raise ContractIRError("refusing symlink user file")
    path.parent.mkdir(parents=True, exist_ok=True)
    if not path.exists():
        with path.open("x", encoding="utf-8") as fp:
            fp.write(body)


def codec_header() -> str:
    # The host-only representation is canonical little-endian, NOT DDS CDR.
    return r"""#pragma once
#include <cstdint>
#include <cstddef>
#include <cstring>
#include <string>
#include <vector>
#include <stdexcept>
namespace generated { namespace codec {
inline void put_long(std::vector<std::uint8_t>& b, std::int32_t x) {
  std::uint32_t bits = 0;
  static_assert(sizeof bits == sizeof x, "32-bit IDL long required");
  std::memcpy(&bits, &x, sizeof bits);
  for (unsigned i=0; i<4; ++i) b.push_back(static_cast<std::uint8_t>(bits >> (8*i)));
}
inline bool get_long(const std::uint8_t*& p, std::size_t& n, std::int32_t& out) {
  if (!p || n<4) return false;
  std::uint32_t bits = 0;
  for (unsigned i=0; i<4; ++i) bits |= std::uint32_t(p[i]) << (8*i);
  std::memcpy(&out, &bits, sizeof out);
  p += 4; n -= 4;
  return true;
}
inline void put_string(std::vector<std::uint8_t>& b, const std::string& s) {
  if (s.size() > 1048576u) throw std::length_error("string exceeds bound");
  put_long(b, static_cast<std::int32_t>(s.size()));
  b.insert(b.end(), s.begin(), s.end());
}
inline bool get_string(const std::uint8_t*& p, std::size_t& n, std::string& s) {
  std::int32_t len = 0;
  if (!get_long(p,n,len) || len < 0 || len > 1048576 || n < static_cast<std::size_t>(len))
    return false;
  s.assign(reinterpret_cast<const char*>(p), static_cast<std::size_t>(len));
  p += len; n -= static_cast<std::size_t>(len);
  return true;
}
}}  // namespace generated::codec
"""


def fields_for(ir: dict, alias: str) -> list[dict]:
    return ir["topics"][alias]["fields"]


def service_type(ir: dict) -> tuple[str, str, list[dict], dict]:
    bindings = ir["protocols"][0]["bindings"]
    if ir["protocols"][0]["kind"] == "command-response":
        alias, kind = bindings["command"], "Command"
    else:
        alias, kind = bindings["reports"][0], "Report"
    return kind, ir["topics"][alias]["idlType"], fields_for(ir, alias), bindings


def render_trait(ir: dict) -> str:
    name = identifier(ir["serviceId"])
    kind, fqtype, fields, binds = service_type(ir)
    topic = ir["topics"][binds["command"] if kind == "Command" else binds["reports"][0]]
    schema = ir["inputs"]["idlSha256"]
    lines = [f"struct {name} {{",
             f'  static constexpr const char* id = "{ir["serviceId"]}";',
             f'  static constexpr const char* schema_id = "{ir["scope"]}:{schema}:{fqtype}";',
             f'  static constexpr bool is_command = {"true" if kind == "Command" else "false"};',
             f'  static constexpr const char* topic_name = {cpp_literal(topic["ddsTopicName"])};',
             f'  static constexpr const char* idl_type = {cpp_literal(topic["idlType"])};',
             f'  static constexpr const char* qos_profile = {cpp_literal(topic["qosProfileRef"])};',
             f"  using {kind} = ::{fqtype};"]
    if kind == "Command":
        for key in ("command", "ack", "status"):
            ref = ir["topics"][binds[key]]
            lines.append(f'  static constexpr const char* {key}_topic = {cpp_literal(ref["ddsTopicName"])};')
            lines.append(f'  static constexpr const char* {key}_schema = "{ir["scope"]}:{schema}:{ref["idlType"]}";')
    method = kind.lower()
    lines += [f"  static std::vector<std::uint8_t> encode_{method}(const {kind}& v) {{",
              "    std::vector<std::uint8_t> b;"]
    for field in fields:
        lines.append(f'    codec::put_{field["type"]}(b, v.{field["name"]});')
    lines += ["    return b;", "  }",
              f"  static bool decode_{method}(const std::uint8_t* p, std::size_t n, {kind}& v) {{",
              "    if (n && !p) return false;", f"    {kind} candidate{{}};"]
    for field in fields:
        lines.append(f'    if (!codec::get_{field["type"]}(p, n, candidate.{field["name"]})) return false;')
    lines += ["    if (n != 0) return false;", "    v = std::move(candidate);",
              "    return true;", "  }", "};"]
    return "\n".join(lines)


def render_handler(ir: dict) -> str:
    name = identifier(ir["serviceId"])
    kind = service_type(ir)[0]
    if kind == "Command":
        method = f"  umaa::Result execute(const generated::{name}::Command&) override {{\n    return umaa::Result::Rejected; // USER IMPLEMENTATION REQUIRED\n  }}"
        base = "CommandHandler"
    else:
        method = (f"  generated::{name}::Report read() override {{\n"
                  '    throw std::runtime_error("device Report handler not implemented");\n  }')
        base = "ReportSource"
    return (f"// USER OWNED; regenerated output never overwrites this file.\n#pragma once\n"
            '#include "generated/service_contracts.hpp"\n#include "umaa/component.hpp"\n'
            '#include <stdexcept>\n'
            f"namespace user {{\nclass {name}Logic final : public umaa::{base}<generated::{name}> {{\n"
            f"public:\n{method}\n}};\n}}\n")


def render_consumer(ir: dict) -> str:
    name = identifier(ir["serviceId"])
    kind = service_type(ir)[0]
    if kind == "Report":
        member = (f"  virtual void on_report(const generated::{name}::Report&, const std::string&) {{}}\n"
                  "  virtual void on_dispose(const std::string&) {}")
    else:
        member = (f"  virtual void request(const generated::{name}::Command&) {{\n"
                  '    throw std::logic_error("remote DDS Command client wiring not implemented");\n  }')
    return (f"// USER OWNED: typed callback skeleton only; NO DDS subscription is started.\n"
            '#pragma once\n#include "generated/service_contracts.hpp"\n'
            '#include <stdexcept>\n#include <string>\n'
            f"namespace user {{\nstruct {name}Consumer {{\n"
            f"  virtual ~{name}Consumer() = default;\n{member}\n}};\n}}\n")


def render_codec_smoke(irs: list[dict]) -> str:
    lines = ['#include "generated/service_contracts.hpp"',
             "#include <cstdint>", "#include <string>", "#include <vector>",
             "int main() {"]
    for i, ir in enumerate(irs):
        name = identifier(ir["serviceId"])
        kind, _, fields, _ = service_type(ir)
        method = kind.lower()
        lines += [f"  generated::{name}::{kind} original{i}{{}};"]
        for field in fields:
            val = '"source-key"' if field["type"] == "string" else "42"
            lines.append(f'  original{i}.{field["name"]} = {val};')
        lines += [f"  const auto bytes{i} = generated::{name}::encode_{method}(original{i});",
                  f"  generated::{name}::{kind} decoded{i}{{}};",
                  f"  if (!generated::{name}::decode_{method}(bytes{i}.data(),bytes{i}.size(),decoded{i})) return {20+i};"]
        for field in fields:
            lines.append(f'  if (decoded{i}.{field["name"]} != original{i}.{field["name"]}) return {40+i};')
        lines += [f"  auto corrupted{i} = bytes{i};",
                  f"  corrupted{i}.push_back(0);",
                  f"  if (generated::{name}::decode_{method}(corrupted{i}.data(),corrupted{i}.size(),decoded{i})) return {60+i};",
                  f"  if (generated::{name}::decode_{method}(bytes{i}.data(),bytes{i}.size()-1,decoded{i})) return {80+i};"]
    lines += ["  return 0;", "}", ""]
    return "\n".join(lines)


def generate(manifest: Path, yaml_paths: list[Path], idl_path: Path,
             output: Path, *, fixture: bool = False, original_icd: Path | None = None) -> dict:
    if not yaml_paths or output.is_symlink():
        raise ContractIRError("expected YAML sources and nonsymlink output")
    doc = cli.validate(json.loads(manifest.read_text(encoding="utf-8")), nonempty=True)
    if doc["component"]["artifact"] != "shared-library":
        raise ContractIRError("only shared-library Components supported")
    irs = [resolve(p, idl_path, fixture=fixture, original_icd=original_icd)
           for p in yaml_paths]
    mapping = {i["serviceId"]: i for i in irs}
    if len(mapping) != len(irs):
        raise ContractIRError("duplicate Service YAML")
    selected_ids = {s["id"] for s in doc["services"]}
    if set(mapping) != selected_ids:
        raise ContractIRError("Component manifest and supplied YAML Service IDs differ")
    for ir in irs:
        blockers = ir["readiness"]["blockers"]
        if blockers:
            raise ContractIRError(ir["serviceId"] + ": " + "; ".join(blockers))
        for topic in ir["topics"].values():
            if any(f["type"] not in {"long", "string"} for f in topic["fields"]):
                raise ContractIRError("restricted encoder supports IDL long/string only")

    # User code is never overwritten. Component ABI v2 registers providers only;
    # consumers are typed scaffold callbacks, not live subscriber endpoints.
    providers = [mapping[s["id"]] for s in doc["services"] if s["role"] == "provider"]
    if not providers:
        raise ContractIRError("consumer-only Component runtime is not implemented")
    types = parse_idl(idl_path.read_text(encoding="utf-8"))
    output.mkdir(parents=True, exist_ok=True)
    write_generated(output / "generated/types.hpp", render_types(types))
    write_generated(output / "generated/codec.hpp", codec_header())
    traits = ['#pragma once', '#include "generated/types.hpp"',
              '#include "generated/codec.hpp"', "#include <utility>",
              "#include <vector>", "#include <string>", "namespace generated {"]
    traits.extend(render_trait(ir) for ir in irs)
    traits += ["} // namespace generated", ""]
    write_generated(output / "generated/service_contracts.hpp", "\n".join(traits))
    registration = [MARK.rstrip(), '#include "umaa/component.hpp"']
    for ir in providers:
        name = identifier(ir["serviceId"])
        write_user(output / f"src/handlers/{name}.hpp", render_handler(ir))
        registration.append(f'#include "src/handlers/{name}.hpp"')
    for item in doc["services"]:
        if item["role"] == "consumer":
            ir = mapping[item["id"]]
            write_user(output / f'src/consumers/{identifier(ir["serviceId"])}.hpp',
                       render_consumer(ir))
    registration += ["namespace {", "void register_services(umaa::Component& c) {"]
    for ir in providers:
        name = identifier(ir["serviceId"])
        registration.append(f"  static user::{name}Logic handler_{name};")
        registration.append(f"  c.provide<generated::{name}>(handler_{name});")
    registration += ["}", "}",
                     f'UMAA_EXPORT_COMPONENT_V2("{doc["component"]["id"]}", register_services)', ""]
    write_generated(output / "generated/component_entry.cpp", "\n".join(registration))
    write_generated(output / "tests/codec_smoke.cpp", render_codec_smoke(irs))
    expected = [f'  if (services[{i}].service != "{ir["serviceId"]}") return {10+i};'
                for i, ir in enumerate(providers)]
    smoke = ['#include "umaa/component_module.hpp"', "#include <string>",
             "int main(int argc, char** argv) {", "  if (argc != 2) return 2;",
             "  umaa::ComponentModule module(argv[1]);",
             f'  if (module.name() != "{doc["component"]["id"]}") return 3;',
             "  const auto& services = module.services();",
             f"  if (services.size() != {len(providers)}) return 4;"]
    smoke += expected + ["  return module.stop() ? 0 : 5;", "}", ""]
    write_generated(output / "tests/module_smoke.cpp", "\n".join(smoke))
    project = doc["component"]["id"]
    d = "$"
    cmake = ["cmake_minimum_required(VERSION 3.20)",
             f"project({project} LANGUAGES CXX)",
             "find_package(UMAAPrototype CONFIG REQUIRED)",
             "enable_testing()",
             f"add_library({project} MODULE generated/component_entry.cpp)",
             f"target_compile_features({project} PRIVATE cxx_std_17)",
             f"target_include_directories({project} PRIVATE {d}{{CMAKE_CURRENT_SOURCE_DIR}})",
             f"target_link_libraries({project} PRIVATE UMAA::Core)",
             "add_executable(contract_codec_smoke tests/codec_smoke.cpp)",
             "target_compile_features(contract_codec_smoke PRIVATE cxx_std_17)",
             f"target_include_directories(contract_codec_smoke PRIVATE {d}{{CMAKE_CURRENT_SOURCE_DIR}})",
             "add_test(NAME contract_codec_smoke COMMAND contract_codec_smoke)",
             "add_executable(component_abi_smoke tests/module_smoke.cpp)",
             "target_compile_features(component_abi_smoke PRIVATE cxx_std_17)",
             "target_link_libraries(component_abi_smoke PRIVATE UMAA::Core)",
             f"add_test(NAME component_abi_smoke COMMAND component_abi_smoke {d}<TARGET_FILE:{project}>)",
             ""]
    write_generated(output / "CMakeLists.txt", "\n".join(cmake), CMAKE_MARK)
    summary = {"componentId": project, "scope": "synthetic-fixture" if fixture else "source-reviewed",
               "serviceIds": sorted(mapping), "providerCount": len(providers),
               "consumerScaffolds": len(doc["services"]) - len(providers),
               "nativeDdsBinding": False,
               "originalYamlHashes": {ir["serviceId"]: ir["inputs"]["yamlSha256"] for ir in irs},
               "idlSha256": irs[0]["inputs"]["idlSha256"],
               "note": "Generated C++ Component v2 skeleton; DDS native TypeBinding not generated"}
    metadata = output / "generated/generation.json"
    if metadata.is_symlink() or any(parent.is_symlink() for parent in metadata.parents):
        raise ContractIRError("refusing symlink metadata")
    if metadata.exists():
        existing = json.loads(metadata.read_text(encoding="utf-8"))
        if existing.get("generatedBy") != "umaa_icd_component_codegen.py":
            raise ContractIRError("refusing overwrite of user-owned metadata")
    summary["generatedBy"] = "umaa_icd_component_codegen.py"
    metadata.write_text(json.dumps(summary, sort_keys=True, indent=2) + "\n",
                        encoding="utf-8")
    return summary


def main(argv: list[str] | None = None) -> int:
    p = argparse.ArgumentParser(description="Source-checked YAML+IDL Component v2 scaffold")
    p.add_argument("--manifest", type=Path, required=True)
    p.add_argument("--yaml", type=Path, action="append", required=True)
    p.add_argument("--idl", type=Path, required=True)
    p.add_argument("--out", type=Path, required=True)
    p.add_argument("--original-icd", type=Path)
    p.add_argument("--fixture", action="store_true",
                   help="explicit Demo:: synthetic fixture; never certifies official UMAA")
    args = p.parse_args(argv)
    try:
        result = generate(args.manifest, args.yaml, args.idl, args.out,
                          fixture=args.fixture, original_icd=args.original_icd)
        print("ICD_COMPONENT_GENERATED: " + json.dumps(result, sort_keys=True))
        return 0
    except (OSError, ValueError, cli.ProjectError) as exc:
        print("ICD_COMPONENT_ERROR: " + str(exc), file=sys.stderr)
        return 2


if __name__ == "__main__":
    raise SystemExit(main())
